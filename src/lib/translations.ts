const lowerEnglish = Object.fromEntries(Object.entries(ENGLISH).map(([key, value]) => [key.toLocaleLowerCase("it"), value]));

export function translateText(text: string, language: AppLanguage): string {
  if (language === "it" || !text.trim()) return text;
  const key = text.trim().replace(/\s+/g, " ");
  const direct = ENGLISH[key] ?? lowerEnglish[key.toLocaleLowerCase("it")];
  if (direct) return text.replace(text.trim(), direct);
  if (text.includes(" · ")) return text.split(" · ").map((part) => translateText(part, language)).join(" · ");
  const quantity = key.match(/^(\d+(?:[.,]\d+)?)\s+(cucchiaio|cucchiai|cucchiaino|cucchiaini|spicchio|spicchi|costa|coste|pezzo|pezzi|pz)$/i);
  if (quantity) {
    const units: Record<string, string> = { cucchiaio: "tbsp", cucchiai: "tbsp", cucchiaino: "tsp", cucchiaini: "tsp", spicchio: "clove", spicchi: "cloves", costa: "stalk", coste: "stalks", pezzo: "piece", pezzi: "pieces", pz: "pcs" };
    return `${quantity[1]!.replace(",", ".")} ${units[quantity[2]!.toLowerCase()]}`;
  }
  if (/^q\.\s*b\.?$/i.test(key)) return "as needed";
  type TextMatch = RegExpMatchArray & { 1: string; 2: string };
  const patterns: Array<[RegExp, (match: TextMatch) => string]> = [
    [/^(?:la|il|gli|le|lo) (.+)$/i, (m) => translateText(m[1], language)],
    [/^Vuoi eliminare il profilo “(.+)”\? Questa operazione non può essere annullata\.$/, (m) => `Delete profile “${m[1]}”? This cannot be undone.`],
    [/^Da sostituire: (.+)$/, (m) => `Needs replacing: ${m[1].split(", ").map((x) => translateText(x, language)).join(", ")}`],
    [/^Elimina ingrediente (.+)$/, (m) => `Delete ingredient ${translateText(m[1], language)}`],
    [/^Elimina (.+)$/, (m) => `Delete ${translateText(m[1], language)}`],
    [/^Scansiona di nuovo, codice precedente (.+)$/, (m) => `Scan again, previous barcode ${m[1]}`],
    [/^Etichetta "senza (.+)" dichiarata dal produttore$/, (m) => `${translateText(m[1], language)}-free claim declared by the manufacturer`],
    [/^Può contenere tracce di (.+), che hai indicato manualmente nel profilo$/, (m) => `May contain traces of ${m[1]}, which you entered in your profile`],
    [/^Può contenere tracce di (.+)$/, (m) => `May contain traces of ${translateText(m[1], language)}`],
    [/^Contiene (.+), che hai indicato manualmente come sostanza\/allergia da evitare$/, (m) => `Contains ${m[1]}, which you entered as a substance/allergen to avoid`],
    [/^Contiene (.+): può contenere lattosio$/, (m) => `Contains ${translateText(m[1], language)}: may contain lactose`],
    [/^Contiene (.+) \(allergene dichiarato\)$/, (m) => `Contains ${translateText(m[1], language)} (declared allergen)`],
    [/^Contiene (.+) \((.+)\)$/, (m) => `Contains ${translateText(m[1], language)} (${translateText(m[2], language)})`],
    [/^Possibile reattività crociata: hai indicato allergia a (.+) e il prodotto contiene (.+)\. Non significa automaticamente allergia a questo alimento: se hai già avuto reazioni, verifica con allergologo\/medico\.$/, (m) => `Possible cross-reactivity: you indicated an allergy to ${translateText(m[1], language)} and the product contains ${translateText(m[2], language)}. This does not automatically mean you are allergic to this food: if you have had reactions, check with an allergist or doctor.`],
    [/^Possibile alimento problematico per sensibilità all'istamina: rilevato “(.+)”\. Il contenuto reale di istamina non si può determinare con certezza dalla sola etichetta e può variare con maturazione, conservazione e fermentazione\.$/, (m) => `Potentially problematic food for histamine sensitivity: “${m[1]}” detected. Actual histamine content cannot be determined reliably from the label alone and may vary with ripening, storage and fermentation.`],
  ];
  for (const [pattern, render] of patterns) { const match = key.match(pattern); if (match) return render(match as TextMatch); }
  return text;
}

export function translateValue<T>(value: T, language: AppLanguage): T {
  return (typeof value === "string" ? translateText(value, language) : value) as T;
}
